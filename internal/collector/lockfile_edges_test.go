// v0.27.133 C2 — parent→child edge extraction fixtures. The C1 parsers
// read most of this data and DISCARDED it (package-lock's per-entry
// dependency maps were decoded into structs and thrown away); these
// fixtures pin that every edge-bearing format now yields edges, that
// yarn-berry (previously ZERO entries, silently) parses fully, and
// that the edge-less Category C formats stay honestly empty.
package collector

import (
	"testing"
)

func edgeSet(edges []LockfileEdge) map[string]string {
	m := map[string]string{}
	for _, e := range edges {
		m[e.ParentName+">"+e.ChildName] = e.Constraint
	}
	return m
}

func TestPackageLockV2Edges(t *testing.T) {
	data := []byte(`{
		"lockfileVersion": 3,
		"packages": {
			"": {"dependencies": {"express": "^4.0.0"}},
			"node_modules/express": {"version": "4.18.2", "dependencies": {"body-parser": "1.20.1"}},
			"node_modules/body-parser": {"version": "1.20.1"}
		}
	}`)
	parsed, err := parsePackageLockJSON(data)
	if err != nil {
		t.Fatal(err)
	}
	es := edgeSet(parsed.Edges)
	if es["express>body-parser"] != "1.20.1" {
		t.Errorf("want express>body-parser edge with its constraint, got %v", es)
	}
}

