// Category C — formats whose files carry NO parent→child data:
// attribution is honestly impossible and edges stay empty.
func TestEdgelessFormatsStayEmpty(t *testing.T) {
	cases := []struct {
		kind string
		data string
	}{
		{"Pipfile.lock", `{"default": {"flask": {"version": "==2.3.0"}}, "develop": {}}`},
		{"pubspec.lock", "packages:\n  http:\n    dependency: \"direct main\"\n    version: \"1.1.0\"\n"},
		{"gradle.lockfile", "org.slf4j:slf4j-api:2.0.9=runtimeClasspath\n"},
	}
	for _, c := range cases {
		res, err := ParseLockfile(c.kind, []byte(c.data))
		if err != nil {
			t.Fatalf("%s: %v", c.kind, err)
		}
		if len(res.Edges) != 0 {
			t.Errorf("%s carries no edge data — parsed edges %v are fabricated", c.kind, res.Edges)
		}
		if len(res.Entries) == 0 {
			t.Errorf("%s: entries lost in the signature conversion", c.kind)
		}
	}
}
